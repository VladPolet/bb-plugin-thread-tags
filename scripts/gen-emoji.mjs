// Regenerates lib/emoji-data.ts from emojibase-data (a devDependency), so the
// app bundle ships a compact list instead of the full 570KB dataset.
// Run: node scripts/gen-emoji.mjs
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(
  readFileSync(new URL("../node_modules/emojibase-data/en/compact.json", import.meta.url)),
);
// Russian labels and tags join the search words, keyed by hexcode.
const ru = new Map(
  JSON.parse(
    readFileSync(new URL("../node_modules/emojibase-data/ru/compact.json", import.meta.url)),
  ).map((entry) => [entry.hexcode, [entry.label, ...(entry.tags ?? [])]]),
);
// emojibase group ids → picker categories. 2 ("component": skin tones, hair)
// is not pickable on its own.
const GROUPS = [
  [0, "smileys", "Smileys", "😀"],
  [1, "people", "People", "👋"],
  [3, "nature", "Animals & nature", "🐶"],
  [4, "food", "Food & drink", "🍔"],
  [5, "travel", "Travel & places", "🚗"],
  [6, "activities", "Activities", "⚽"],
  [7, "objects", "Objects", "💡"],
  [8, "symbols", "Symbols", "❤️"],
  [9, "flags", "Flags", "🏁"],
];
const categories = GROUPS.map(([group, id, label, icon]) => ({
  id,
  label,
  icon,
  // "emoji|search words" keeps the file small and needs no per-entry objects.
  emojis: data
    .filter((entry) => entry.group === group)
    .sort((a, b) => a.order - b.order)
    .map((entry) =>
      `${entry.unicode}|${[...new Set([entry.label, ...(entry.tags ?? []), ...(ru.get(entry.hexcode) ?? [])])].join(" ").toLowerCase()}`.replaceAll('"', ""),
    ),
}));
const version = JSON.parse(
  readFileSync(new URL("../node_modules/emojibase-data/package.json", import.meta.url)),
).version;
writeFileSync(
  new URL("../lib/emoji-data.ts", import.meta.url),
  `// Generated by scripts/gen-emoji.mjs from emojibase-data ${version}. Do not edit.\n` +
    `export interface EmojiCategory {\n  id: string;\n  label: string;\n  icon: string;\n  /** "emoji|lowercase search words" */\n  emojis: string[];\n}\n\n` +
    `export const EMOJI_CATEGORIES: EmojiCategory[] = ${JSON.stringify(categories, null, 1)};\n`,
);
console.log(categories.map((c) => `${c.id}: ${c.emojis.length}`).join(", "));
